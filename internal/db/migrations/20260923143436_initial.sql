CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID,
    actor_id UUID REFERENCES users (id) ON DELETE SET NULL,
    actor_kind TEXT NOT NULL,
    action TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id TEXT NOT NULL DEFAULT '',
    subject_id UUID REFERENCES users (id) ON DELETE SET NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    ip TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT audit_log_actor_kind_check CHECK (actor_kind IN ('user', 'staff', 'system')),
    CONSTRAINT audit_log_details_object CHECK (jsonb_typeof(details) = 'object')
);
CREATE INDEX idx_audit_log_site_created ON audit_log (created_at DESC, id DESC) WHERE org_id IS NULL;
CREATE INDEX idx_audit_log_subject_created ON audit_log (subject_id, created_at DESC) WHERE subject_id IS NOT NULL;
CREATE INDEX idx_audit_log_actor_id ON audit_log (actor_id) WHERE actor_id IS NOT NULL;
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at);

CREATE TABLE user_identities (
    provider TEXT NOT NULL,
    subject TEXT NOT NULL,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    email CITEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (provider, subject),
    CONSTRAINT user_identities_user_provider_key UNIQUE (user_id, provider),
    CONSTRAINT user_identities_provider_check CHECK (provider IN ('google')),
    CONSTRAINT user_identities_subject_length CHECK (char_length(subject) BETWEEN 1 AND 255)
);

CREATE TABLE oidc_flows (
    token_hash TEXT PRIMARY KEY,
    provider TEXT NOT NULL,
    purpose TEXT NOT NULL,
    state TEXT NOT NULL,
    nonce TEXT NOT NULL,
    code_verifier TEXT NOT NULL,
    user_id UUID REFERENCES users (id) ON DELETE CASCADE,
    session_token_hash TEXT REFERENCES sessions (token) ON DELETE CASCADE,
    return_to TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT oidc_flows_provider_check CHECK (provider IN ('google')),
    CONSTRAINT oidc_flows_purpose_check CHECK (purpose IN ('sign_in', 'link')),
    CONSTRAINT oidc_flows_link_has_user CHECK ((purpose = 'link') = (user_id IS NOT NULL)),
    CONSTRAINT oidc_flows_link_has_session CHECK ((purpose = 'link') = (session_token_hash IS NOT NULL)),
    CONSTRAINT oidc_flows_state_length CHECK (char_length(state) >= 43),
    CONSTRAINT oidc_flows_nonce_length CHECK (char_length(nonce) >= 43),
    CONSTRAINT oidc_flows_code_verifier_length CHECK (char_length(code_verifier) BETWEEN 43 AND 128)
);
CREATE INDEX idx_oidc_flows_expires_at ON oidc_flows (expires_at);

CREATE TABLE invitations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email CITEXT NOT NULL,
    token_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT invitations_email_key UNIQUE (email),
    CONSTRAINT invitations_token_hash_key UNIQUE (token_hash),
    CONSTRAINT invitations_email_length CHECK (char_length(email) BETWEEN 3 AND 254)
);

