CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE site_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by UUID
);

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email CITEXT NOT NULL,
    password_hash TEXT,
    display_name TEXT NOT NULL DEFAULT '',
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    email_notifications BOOLEAN NOT NULL DEFAULT TRUE,
    banned_at TIMESTAMPTZ,
    banned_by UUID REFERENCES users (id) ON DELETE SET NULL,
    ban_reason TEXT NOT NULL DEFAULT '',
    locked_at TIMESTAMPTZ,
    locked_by UUID REFERENCES users (id) ON DELETE SET NULL,
    lock_reason TEXT NOT NULL DEFAULT '',
    last_seen_ip TEXT,
    last_seen_ip_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_email_length CHECK (char_length(email) BETWEEN 3 AND 254),
    CONSTRAINT users_display_name_length CHECK (char_length(display_name) <= 40)
);
CREATE INDEX idx_users_banned_by ON users (banned_by) WHERE banned_by IS NOT NULL;
CREATE INDEX idx_users_locked_by ON users (locked_by) WHERE locked_by IS NOT NULL;

CREATE TABLE sessions (
    token TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_sessions_user_id ON sessions (user_id);
CREATE INDEX idx_sessions_expires_at ON sessions (expires_at);

CREATE TABLE email_verification_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    pending_email CITEXT,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_email_verification_tokens_user_id ON email_verification_tokens (user_id);

CREATE TABLE password_reset_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_password_reset_tokens_user_id ON password_reset_tokens (user_id);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    org_id UUID,
    type TEXT NOT NULL,
    reference_type TEXT NOT NULL DEFAULT '',
    reference_id UUID,
    actor_id UUID REFERENCES users (id) ON DELETE SET NULL,
    message TEXT NOT NULL DEFAULT '',
    read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT notifications_type_check CHECK (type IN ('org_invite', 'action_item_assigned', 'payment_failed', 'trial_ending', 'payment_refunded', 'payment_disputed', 'org_dormant'))
);
CREATE INDEX idx_notifications_user_created ON notifications (user_id, created_at DESC);
CREATE INDEX idx_notifications_created_at ON notifications (created_at);
CREATE INDEX idx_notifications_actor_id ON notifications (actor_id) WHERE actor_id IS NOT NULL;

CREATE TABLE user_roles (
    user_id UUID PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    CONSTRAINT user_roles_role_check CHECK (role IN ('super_admin', 'admin', 'support'))
);

CREATE TABLE role_permissions (
    role TEXT NOT NULL,
    permission TEXT NOT NULL,
    PRIMARY KEY (role, permission),
    CONSTRAINT role_permissions_editable_role_only CHECK (role = 'support')
);

